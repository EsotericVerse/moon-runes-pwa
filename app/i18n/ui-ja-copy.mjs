function translateSiteCopy(value){
  if(typeof value==='string')return JA_FIELDS[value]||JA_UI_EXTRA[value]||value;
  if(typeof value==='function')return value;
  if(Array.isArray(value))return Object.freeze(value.map(translateSiteCopy));
  if(value&&typeof value==='object')return Object.freeze(Object.fromEntries(
    Object.entries(value).map(([key,item])=>[key,translateSiteCopy(item)])
  ));
  return value;
}

