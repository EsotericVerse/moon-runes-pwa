-- Replace the imported rune literature JSON dump with typed PostgreSQL columns.
-- The text field was verified to equal body for all 559 rune_literature rows.
-- Nested rune objects are preserved as ordered typed arrays, never as JSON.
BEGIN;
ALTER TABLE silver.lrunes_literature
  ADD COLUMN entry_id text,
  ADD COLUMN chapter integer,
  ADD COLUMN chapter_label text,
  ADD COLUMN confidence text,
  ADD COLUMN confirmation_type text,
  ADD COLUMN confirmation_statement text,
  ADD COLUMN confirmation_confirmed boolean,
  ADD COLUMN core_positions integer[],
  ADD COLUMN core_runes text[],
  ADD COLUMN source_created_date text,
  ADD COLUMN source_date text,
  ADD COLUMN draw_provenance_status text,
  ADD COLUMN era_name text,
  ADD COLUMN form text,
  ADD COLUMN generation_method text,
  ADD COLUMN source_group text,
  ADD COLUMN group_statistics_status text,
  ADD COLUMN lyric_rune_hits text[],
  ADD COLUMN metadata_status text,
  ADD COLUMN moon_phase text,
  ADD COLUMN part integer,
  ADD COLUMN part_name text,
  ADD COLUMN period text,
  ADD COLUMN rune_configuration_canonical_names text[],
  ADD COLUMN rune_configuration_legacy_names text[],
  ADD COLUMN rune_configuration_orientations text[],
  ADD COLUMN rune_count integer,
  ADD COLUMN rune_name text,
  ADD COLUMN rune_number integer,
  ADD COLUMN rune_song_flag boolean,
  ADD COLUMN rune_system_basis text,
  ADD COLUMN rune_system_category text,
  ADD COLUMN rune_system_content_type text,
  ADD COLUMN rune_system_group_status text,
  ADD COLUMN rune_system_specific_status text,
  ADD COLUMN rune_system_tag text,
  ADD COLUMN rune_song_names text[],
  ADD COLUMN rune_song_orientations text[],
  ADD COLUMN rune_song_positions integer[],
  ADD COLUMN search_policy text,
  ADD COLUMN source_line integer,
  ADD COLUMN source_outline text,
  ADD COLUMN source_platform text,
  ADD COLUMN source_title text,
  ADD COLUMN source_type text,
  ADD COLUMN special_construction boolean,
  ADD COLUMN source_status text,
  ADD COLUMN suno_status text,
  ADD COLUMN suno_url text,
  ADD COLUMN work_id text,
  ADD COLUMN source_tags text[],
  ADD COLUMN relation_note text,
  ADD COLUMN matched_rune_canonical_names text[],
  ADD COLUMN matched_rune_legacy_names text[],
  ADD COLUMN matched_rune_orientations text[],
  ADD COLUMN recovery_contains_fu boolean,
  ADD COLUMN recovery_contains_huo boolean,
  ADD COLUMN recovery_distinct_rune_hits integer,
  ADD COLUMN recovery_high_signal_rune_hits integer,
  ADD COLUMN recovery_note text,
  ADD COLUMN analysis_summary text;
UPDATE silver.lrunes_literature l SET
  entry_id=l.source_payload->>'entry_id',
  chapter=(l.source_payload->>'chapter')::integer,
  chapter_label=l.source_payload->>'chapter_label',
  confidence=l.source_payload->>'confidence',
  confirmation_type=l.source_payload->'confirmation'->>'type',
  confirmation_statement=l.source_payload->'confirmation'->>'statement',
  confirmation_confirmed=(l.source_payload->'confirmation'->>'confirmed_in_current_review')::boolean,
  core_positions=ARRAY(SELECT jsonb_array_elements_text(COALESCE(l.source_payload->'core_positions','[]'::jsonb))::integer),
  core_runes=ARRAY(SELECT jsonb_array_elements_text(COALESCE(l.source_payload->'core_runes','[]'::jsonb))),
  source_created_date=l.source_payload->>'created_date',
  source_date=l.source_payload->>'date',
  draw_provenance_status=l.source_payload->>'draw_provenance_status',
  era_name=l.source_payload->>'era_name',
  form=l.source_payload->>'form',
  generation_method=l.source_payload->>'generation_method',
  source_group=l.source_payload->>'group',
  group_statistics_status=l.source_payload->>'group_statistics_status',
  lyric_rune_hits=ARRAY(SELECT jsonb_array_elements_text(COALESCE(l.source_payload->'lyric_rune_hits','[]'::jsonb))),
  metadata_status=l.source_payload->>'metadata_status',
  moon_phase=l.source_payload->>'moon_phase',
  part=(l.source_payload->>'part')::integer,
  part_name=l.source_payload->>'part_name',
  period=l.source_payload->>'period',
  rune_configuration_canonical_names=COALESCE((SELECT array_agg(a.elem->>'canonical_name' ORDER BY a.ordinality) FROM jsonb_array_elements(CASE WHEN jsonb_typeof(l.source_payload->'rune_configuration')='array' THEN l.source_payload->'rune_configuration' ELSE '[]'::jsonb END) WITH ORDINALITY AS a(elem,ordinality)),ARRAY[]::text[]),
  rune_configuration_legacy_names=COALESCE((SELECT array_agg(a.elem->>'legacy_name' ORDER BY a.ordinality) FROM jsonb_array_elements(CASE WHEN jsonb_typeof(l.source_payload->'rune_configuration')='array' THEN l.source_payload->'rune_configuration' ELSE '[]'::jsonb END) WITH ORDINALITY AS a(elem,ordinality)),ARRAY[]::text[]),
  rune_configuration_orientations=COALESCE((SELECT array_agg(a.elem->>'orientation' ORDER BY a.ordinality) FROM jsonb_array_elements(CASE WHEN jsonb_typeof(l.source_payload->'rune_configuration')='array' THEN l.source_payload->'rune_configuration' ELSE '[]'::jsonb END) WITH ORDINALITY AS a(elem,ordinality)),ARRAY[]::text[]),
  rune_count=(l.source_payload->>'rune_count')::integer,
  rune_name=l.source_payload->>'rune_name',
  rune_number=(l.source_payload->>'rune_number')::integer,
  rune_song_flag=(l.source_payload->>'rune_song_flag')::boolean,
  rune_system_basis=l.source_payload->'rune_system'->>'basis',
  rune_system_category=l.source_payload->'rune_system'->>'category',
  rune_system_content_type=l.source_payload->'rune_system'->>'content_type',
  rune_system_group_status=l.source_payload->'rune_system'->>'group_status',
  rune_system_specific_status=l.source_payload->'rune_system'->>'specific_system_status',
  rune_system_tag=l.source_payload->'rune_system'->>'tag',
  rune_song_names=COALESCE((SELECT array_agg(a.elem->>'rune' ORDER BY a.ordinality) FROM jsonb_array_elements(CASE WHEN jsonb_typeof(l.source_payload->'runes')='array' THEN l.source_payload->'runes' ELSE '[]'::jsonb END) WITH ORDINALITY AS a(elem,ordinality)),ARRAY[]::text[]),
  rune_song_orientations=COALESCE((SELECT array_agg(a.elem->>'orientation' ORDER BY a.ordinality) FROM jsonb_array_elements(CASE WHEN jsonb_typeof(l.source_payload->'runes')='array' THEN l.source_payload->'runes' ELSE '[]'::jsonb END) WITH ORDINALITY AS a(elem,ordinality)),ARRAY[]::text[]),
  rune_song_positions=COALESCE((SELECT array_agg((a.elem->>'position')::integer ORDER BY a.ordinality) FROM jsonb_array_elements(CASE WHEN jsonb_typeof(l.source_payload->'runes')='array' THEN l.source_payload->'runes' ELSE '[]'::jsonb END) WITH ORDINALITY AS a(elem,ordinality)),ARRAY[]::integer[]),
  search_policy=l.source_payload->>'search_policy',
  source_line=(l.source_payload->>'source_line')::integer,
  source_outline=l.source_payload->>'source_outline',
  source_platform=l.source_payload->>'source_platform',
  source_title=l.source_payload->>'source_title',
  source_type=l.source_payload->>'source_type',
  special_construction=(l.source_payload->>'special_construction')::boolean,
  source_status=l.source_payload->>'status',
  suno_status=l.source_payload->>'suno_status',
  suno_url=l.source_payload->>'suno_url',
  work_id=l.source_payload->>'work_id',
  source_tags=ARRAY(SELECT jsonb_array_elements_text(COALESCE(l.source_payload->'tags','[]'::jsonb))),
  relation_note=l.source_payload->>'relation_note',
  matched_rune_canonical_names=COALESCE((SELECT array_agg(a.elem->>'canonical_name' ORDER BY a.ordinality) FROM jsonb_array_elements(CASE WHEN jsonb_typeof(l.source_payload->'matched_rune_sources')='array' THEN l.source_payload->'matched_rune_sources' ELSE '[]'::jsonb END) WITH ORDINALITY AS a(elem,ordinality)),ARRAY[]::text[]),
  matched_rune_legacy_names=COALESCE((SELECT array_agg(a.elem->>'legacy_name' ORDER BY a.ordinality) FROM jsonb_array_elements(CASE WHEN jsonb_typeof(l.source_payload->'matched_rune_sources')='array' THEN l.source_payload->'matched_rune_sources' ELSE '[]'::jsonb END) WITH ORDINALITY AS a(elem,ordinality)),ARRAY[]::text[]),
  matched_rune_orientations=COALESCE((SELECT array_agg(a.elem->>'orientation' ORDER BY a.ordinality) FROM jsonb_array_elements(CASE WHEN jsonb_typeof(l.source_payload->'matched_rune_sources')='array' THEN l.source_payload->'matched_rune_sources' ELSE '[]'::jsonb END) WITH ORDINALITY AS a(elem,ordinality)),ARRAY[]::text[]),
  recovery_contains_fu=(l.source_payload->'recovery_evidence'->>'contains_fu')::boolean,
  recovery_contains_huo=(l.source_payload->'recovery_evidence'->>'contains_huo')::boolean,
  recovery_distinct_rune_hits=(l.source_payload->'recovery_evidence'->>'distinct_rune_hits')::integer,
  recovery_high_signal_rune_hits=(l.source_payload->'recovery_evidence'->>'high_signal_rune_hits')::integer,
  recovery_note=l.source_payload->'recovery_evidence'->>'note',
  analysis_summary=l.source_payload->>'analysis_summary',
  source_tags=ARRAY(SELECT jsonb_array_elements_text(COALESCE(l.source_payload->'tags','[]'::jsonb)));
UPDATE silver.lrunes_literature l SET tags=source_tags;
ALTER TABLE silver.lrunes_literature DROP COLUMN source_payload;
COMMIT;
