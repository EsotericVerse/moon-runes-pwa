import assert from 'node:assert/strict';
import {DATABASE_ENGINES,normalizeDatabaseTarget,selectedDatabaseTarget,selectedDatabaseProvider} from '../app/loc/providers/selected-database-target.mjs';
assert.deepEqual(DATABASE_ENGINES,['postgres','mysql','mssql','sqlite']);
assert.equal(selectedDatabaseProvider([{provider:'supabase',selected:true}]),'supabase');
assert.equal(selectedDatabaseTarget([{provider:'neon',selected:true}]).engine,'postgres');
assert.equal(normalizeDatabaseTarget({provider:'custom',engine:'mysql',connection_alias:'client_mysql'}).engine,'mysql');
assert.equal(normalizeDatabaseTarget({provider:'custom',engine:'mssql',connection_alias:'azure_sql'}).connection_alias,'azure_sql');
assert.throws(()=>normalizeDatabaseTarget({provider:'custom',engine:'mysql',connection_alias:'../../secret'}),/alias/);
assert.throws(()=>normalizeDatabaseTarget({provider:'supabase',engine:'mysql'}),/engine/);
assert.throws(()=>selectedDatabaseTarget([{provider:'supabase',selected:true},{provider:'neon',selected:true}]),/More than one/);
assert.throws(()=>normalizeDatabaseTarget({provider:'custom',engine:'sqlite',connection_alias:'local'}),/persistent/);
console.log('[database-targets] Driver selection, managed aliases, legacy targets and fail-closed validation passed');
