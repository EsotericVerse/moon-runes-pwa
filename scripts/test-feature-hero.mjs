import assert from 'node:assert/strict';
import {HomeBlock} from '../app/loc/home-block-model.js';

assert.equal(HomeBlock.FEATURE_HERO_PAGE,'feature_hero');
assert.deepEqual(HomeBlock.FEATURE_HERO_IDS,['culture','statics','search','governance']);
assert.equal(new Set(Object.values(HomeBlock.FEATURE_HERO_ORDER)).size,4);
assert.deepEqual(Object.values(HomeBlock.FEATURE_HERO_ORDER),[1,2,3,4]);

const rows=HomeBlock.FEATURE_HERO_IDS.map(featureId=>({
  page_name:HomeBlock.FEATURE_HERO_PAGE,
  block_order:HomeBlock.FEATURE_HERO_ORDER[featureId],
  block_title:'Title of '+featureId,
  block_eyebrow:'English of '+featureId,
  block_subtitle:'<p><strong>Rich '+featureId+'</strong></p>',
  block_text:'<p>Canonical '+featureId+'</p>'
}));
for(const feature of HomeBlock.FEATURE_HERO_IDS){
  const heading=HomeBlock.featureHeroFor(rows,feature);
  assert.equal(heading.eyebrow,'English of '+feature);
  assert.equal(heading.title,'Title of '+feature);
  assert.equal(heading.subtitle,'<p><strong>Rich '+feature+'</strong></p>');
  assert.equal(heading.description,'<p>Canonical '+feature+'</p>');
  for(const scope of ['loc','lo3rwang','sample']){
    assert.equal(HomeBlock.shouldUseSharedFeatureHero(scope,feature),true);
  }
  assert.equal(HomeBlock.shouldUseSharedFeatureHero('lrunes',feature),false,'LunaRunes must stay on existing copy');
  assert.equal(HomeBlock.shouldUseSharedFeatureHero('admin',feature),false);
}
assert.equal(HomeBlock.shouldUseSharedFeatureHero('loc','home'),false);
assert.equal(HomeBlock.featureHeroFor(rows,'home'),null);
assert.equal(HomeBlock.featureHeroFor([], 'culture'),null);
assert.equal(HomeBlock.featureHeroFor([{...rows[0],page_name:'index'}],'culture'),null,
  'index blocks must never be mistaken for feature headers');
assert.equal(HomeBlock.featureHeroFor([{...rows[0],block_eyebrow:''}],'culture').eyebrow,'',
  'empty eyebrow must remain editable without being autogenerated');
assert.equal(HomeBlock.featureHeroFor([{...rows[0],block_title:''}],'culture').title,'',
  'empty custom title must still be a distinguishable stored row');
console.log('[feature-hero] one LOC-managed source, four features, scope sharing, rune isolation and fallbacks verified');

// Cross-capability behavior: one object handles pages, child cards and hero extensions.
assert.equal(HomeBlock.limit,8);
assert.equal(HomeBlock.rows([{uid:'A',page_name:'index',block_order:1}]).length,1);
assert.equal(HomeBlock.childPresentation(''),'bubble');
assert.equal(HomeBlock.visibleEntities({title:'Start',entities:[{uid:'child',title:'Note',text:'Body'}]}).length,1);
assert.equal(HomeBlock.featureHeroFor(rows,'culture').title,'Title of culture');
